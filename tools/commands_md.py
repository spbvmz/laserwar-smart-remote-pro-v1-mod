#!/usr/bin/env python3
"""Write docs/commands.md: command bytes of every command list in the menu."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from patcher import menu as m  # noqa: E402


def c2(c0: int, c1: int) -> int:
    return c0 ^ c1 if c0 >= 0xB0 else 0xE8


def table(groups: list, names: dict | None = None) -> list[str]:
    names = {**m.CMD_NAMES, **(names or {})}
    out = []
    for g_ru, g_en, cmds in groups:
        out += [f"**{g_ru} / {g_en}**", "", "| Команда | Command | Байты / Bytes |", "|---|---|---|"]
        for c0, c1 in cmds:
            ru, en = names[(c0, c1)]
            out.append(f"| {ru} | {en} | `{c0:02X} {c1:02X} {c2(c0, c1):02X}` |")
        out.append("")
    return out


def section(title: str, where: str, groups: list, names: dict | None = None) -> list[str]:
    n = sum(len(c) for _g, _e, c in groups)
    return [f"## {title}", "", f"{where}.", "", f"Всего / total: {n}.", ""] + table(groups, names)


def main() -> None:
    point = [(g_ru, g_en, [(v >> 8, v & 0xFF) for _r, _e, v in items]) for g_ru, g_en, items in m.PULSE_GROUPS]
    lines = [
        "# Байты команд / Command bytes",
        "",
        "<!-- generated by tools/commands_md.py, do not edit -->",
        "",
        "Все списки команд меню «Девайсы». Байты `c0 c1 c2`: код команды, аргумент и третий байт "
        "(`c0 XOR c1`, если `c0 >= B0`, иначе `E8`). Как они записываются в устройства: "
        "[protocol.md](protocol.md).",
        "",
        "All command lists of the Devices menu. Bytes `c0 c1 c2`: command code, argument and the third byte "
        "(`c0 XOR c1` if `c0 >= B0`, else `E8`). How they are written to devices: [protocol.md](protocol.md).",
        "",
    ]
    lines += section(
        "Точка: команды импульсов / Point: pulse commands",
        "Регистр точки: младший байт = `c1`, старший = `c0`; регистры 4, 10, 16, 32, 34 / "
        "Point register: low byte = `c1`, high = `c0`; registers 4, 10, 16, 32, 34",
        point)
    lines += section("Умная аптечка 2.0: команда Здоровье / Smart medkit 2.0: Health command",
                     "Адреса / Addresses 21..23", m.FAK_HEALTH_CMDS)
    lines += section("Умная аптечка 2.0: команда Боезапас / Smart medkit 2.0: Ammo command",
                     "Адреса / Addresses 37..39", [("Боезапас", "Ammo", m.FAK_AMMO_CMDS)])
    lines += section("Умная аптечка 2.0: команда Энергия / Smart medkit 2.0: Energy command",
                     "Адреса / Addresses 53..55", m.FAK_ENERGY_CMDS)
    lines += section("Умный медик: команда / Smart medic: command",
                     "Адреса / Addresses 23..25", m.MED_CMDS)
    lines += section("Командный пункт: при захвате и противостояние / Command post: capture and 2x2",
                     "Адреса / Addresses 177..179 (захват / capture), 183..185 (противостояние / 2x2)",
                     m.CP2_CMDS, m.CP2_NAMES)
    lines += section("Командный пункт: аптечка / Command post: medkit",
                     "Адреса / Addresses 180..182", [("Аптечка", "Medkit", m.CP2_FAK_CMDS)])
    out = ROOT / "docs" / "commands.md"
    out.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"written {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
